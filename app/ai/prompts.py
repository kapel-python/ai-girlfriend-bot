def build_system_prompt(personality_key: str, custom_prompt: str, mood: str = "") -> str:
    """Собирает полный system prompt из слоёв: система + характер + настроение + custom."""
    parts = [SYSTEM_PROMPT]

    preset = PERSONALITY_PRESETS.get(personality_key, PERSONALITY_PRESETS["default"])
    parts.append(f"\nТвой характер:\n{preset['prompt']}")

    if mood.strip():
        parts.append(f"\nТвоё настроение сейчас: {mood.strip()}. Учитывай его в тоне ответов.")

    if custom_prompt.strip():
        parts.append(f"\nДополнительные пожелания собеседника (учитывай, но не нарушай правила выше):\n{custom_prompt.strip()}")

    return "\n".join(parts)


